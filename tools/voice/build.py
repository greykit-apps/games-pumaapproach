#!/usr/bin/env python3
"""build.py -- turn the recorded words into the game's embedded ESS-style voice.

Electronic Speech Systems' "Software Speech" (the voice in Kennedy Approach)
was a recorded human voice, band-limited, cut to single words, and played back
as 4-bit samples through the SID's volume register. This does the same thing to
our own recordings: trim, band-pass, resample to 8 kHz, quantise to 4 bits,
pack two samples per byte, and write the lot as one base64 string between the
/* @voice-begin */ ... /* @voice-end */ sentinels in index.html.

  python -I tools/voice/build.py --wav-dir <dir> --out index.html [--preview <dir>]

--radio <wav> does the same to one whole recorded phrase instead, the boot's
transmission (tools/voice/radio.sh records it), between the @radio sentinels:

  python -I tools/voice/build.py --radio <wav> --out index.html [--preview <dir>]

--preview writes each processed word back out as an 8 kHz WAV so you can hear
what the game will say. Needs numpy only.
"""
import argparse, base64, json, os, re, sys, wave
import numpy as np

RATE = 8000          # playback rate; Web Audio's createBuffer accepts 8 kHz everywhere
LO, HI = 280.0, 3100.0   # the phone band ESS lived in
BITS = 4

def read_wav(path):
    with wave.open(path, "rb") as w:
        sr, n, sw, ch = w.getframerate(), w.getnframes(), w.getsampwidth(), w.getnchannels()
        raw = w.readframes(n)
    assert sw == 2, "16-bit WAVs only"
    x = np.frombuffer(raw, dtype="<i2").astype(np.float64) / 32768.0
    if ch > 1: x = x.reshape(-1, ch).mean(axis=1)
    return sr, x

def trim(x, sr, thresh=0.015, pad_ms=25):
    env = np.abs(x)
    win = max(1, sr // 200)
    env = np.convolve(env, np.ones(win) / win, mode="same")
    idx = np.where(env > thresh)[0]
    if len(idx) == 0: return x
    pad = int(sr * pad_ms / 1000)
    return x[max(0, idx[0] - pad): min(len(x), idx[-1] + pad)]

def bandpass(x, sr):
    n = len(x)
    X = np.fft.rfft(x, n=1 << (n - 1).bit_length())
    f = np.fft.rfftfreq(len(X) * 2 - 2, 1.0 / sr)
    g = np.ones_like(f)
    g[f < LO] = np.clip((f[f < LO] / LO) ** 4, 0, 1)          # soft high-pass
    g[f > HI] = np.exp(-((f[f > HI] - HI) / 250.0) ** 2)        # soft low-pass
    return np.fft.irfft(X * g)[:n]

def resample(x, sr, to):
    t_old = np.arange(len(x)) / sr
    t_new = np.arange(0, t_old[-1], 1.0 / to)
    return np.interp(t_new, t_old, x)

def squash(x):
    # a little compression so the quiet consonants survive 4 bits, like a
    # 1985 cassette-deck mic chain would have done
    x = x / (np.max(np.abs(x)) + 1e-9)
    y = np.tanh(x * 2.2) / np.tanh(2.2)
    return y / (np.max(np.abs(y)) + 1e-9) * 0.97

def quantise(x):
    levels = (1 << BITS) - 1
    q = np.round((x + 1.0) / 2.0 * levels)
    return np.clip(q, 0, levels).astype(np.uint8)

def pack(q):
    if len(q) % 2: q = np.append(q, [levels_mid()])
    return (q[0::2] | (q[1::2] << 4)).astype(np.uint8).tobytes()

def levels_mid(): return ((1 << BITS) - 1) // 2

def write_wav(path, q, rate):
    x = ((q.astype(np.float64) / ((1 << BITS) - 1)) * 2 - 1) * 0.9
    with wave.open(path, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate)
        w.writeframes((x * 32767).astype("<i2").tobytes())

def load_words(path):
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"): continue
        key, text = line.split("|", 2)[:2]
        out.append((key.strip(), text.strip()))
    return out

def process(path):
    sr, x = read_wav(path)
    x = trim(x, sr)
    x = bandpass(x, sr)
    x = resample(x, sr, RATE)
    x = squash(x)
    q = quantise(x)
    if len(q) % 2: q = np.append(q, [levels_mid()]).astype(np.uint8)
    return q

def write_block(out, name, block):
    src = open(out, encoding="utf-8").read()
    new, n = re.subn(r"/\* @%s-begin[\s\S]*?@%s-end \*/" % (name, name), lambda m: block, src)
    if n != 1:
        print("no @%s block in" % name, out, file=sys.stderr); sys.exit(1)
    open(out, "w", encoding="utf-8", newline="\n").write(new)
    print("wrote", out)

def radio(a):
    q = process(a.radio)
    if a.preview:
        os.makedirs(a.preview, exist_ok=True)
        write_wav(os.path.join(a.preview, "radio.wav"), q, RATE)
    b64 = base64.b64encode(pack(q)).decode("ascii")
    block = ("/* @radio-begin -- generated by tools/voice/build.py --radio from tools/voice/radio.sh:\n"
             " * %d samples at %d Hz, %d-bit, two per byte. Do not edit by hand. */\n"
             "const RADIO = {rate:%d,bits:%d,data:\"%s\"};\n/* @radio-end */") % (len(q), RATE, BITS, RATE, BITS, b64)
    print("radio: %.1f s of speech, %d bytes base64" % (len(q) / RATE, len(b64)))
    if a.out: write_block(a.out, "radio", block)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wav-dir", help="one WAV per words.txt key")
    ap.add_argument("--radio", help="one WAV of the boot's transmission, instead of --wav-dir")
    ap.add_argument("--out", help="index.html to rewrite between the @voice (or @radio) sentinels")
    ap.add_argument("--preview", help="directory for the processed 8 kHz WAVs")
    a = ap.parse_args()
    if a.radio: return radio(a)
    if not a.wav_dir: ap.error("--wav-dir or --radio")
    here = os.path.dirname(os.path.abspath(__file__))
    words = load_words(os.path.join(here, "words.txt"))
    idx, chunks, pos = {}, [], 0
    for key, text in words:
        path = os.path.join(a.wav_dir, key + ".wav")
        if not os.path.exists(path):
            print("missing", path, file=sys.stderr); sys.exit(1)
        q = process(path)
        if a.preview:
            os.makedirs(a.preview, exist_ok=True)
            write_wav(os.path.join(a.preview, key + ".wav"), q, RATE)
        idx[key] = [pos, len(q)]
        chunks.append(q); pos += len(q)
    allq = np.concatenate(chunks)
    packed = pack(allq)
    b64 = base64.b64encode(packed).decode("ascii")
    block = ("/* @voice-begin -- generated by tools/voice/build.py from tools/voice/words.txt:\n"
             " * %d words, %d samples at %d Hz, %d-bit, two per byte. Do not edit by hand. */\n"
             "const VOICE = {rate:%d,bits:%d,idx:%s,data:\"%s\"};\n/* @voice-end */") % (
        len(words), len(allq), RATE, BITS, RATE, BITS, json.dumps(idx, separators=(",", ":")), b64)
    print("%d words, %.1f s of speech, %d bytes packed, %d bytes base64" % (len(words), len(allq) / RATE, len(packed), len(b64)))
    if a.out: write_block(a.out, "voice", block)

if __name__ == "__main__":
    main()
